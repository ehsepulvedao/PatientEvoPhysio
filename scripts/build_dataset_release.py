#!/usr/bin/env python3
"""Build an upload-ready research-data package from generated curated runs."""
from __future__ import annotations
import argparse,csv,hashlib,json,shutil,zipfile
from datetime import datetime,timezone
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]; GEN=ROOT/'data'/'generated'

def sha(p):
 h=hashlib.sha256();
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1024*1024),b''): h.update(b)
 return h.hexdigest()

def unit_desc(name):
 if name=='time': return ('s','Simulation time')
 l=name.lower()
 if 'pressure_mmhg' in l:return ('mmHg','Pressure converted for physiological interpretation')
 if 'flow_l_per_min' in l:return ('L/min','Volumetric blood flow')
 if l.endswith('.volume'):return ('m3','Blood volume in SI units; multiply by 1e6 for mL')
 if 'oxygensaturation' in l:return ('%','Oxygen saturation in percentage points')
 if l.endswith('.open'):return ('0/1','Valve state: 1 open, 0 closed')
 if l.endswith('.hp'):return ('s','Cardiac period')
 if l.endswith('.e'):return ('Pa/m3','Elastance, model SI unit')
 if l.endswith('.r'):return ('Pa.s/m3','Hydraulic resistance, model SI unit')
 if 'metabolicconsumptionrate' in l:return ('mol/s','Metabolic oxygen consumption rate')
 if 'o2_current' in l or l.endswith('.conc'):return ('mol/m3','Oxygen concentration')
 return ('','See PatientEvoPhysio model definition and metadata')

ap=argparse.ArgumentParser(); ap.add_argument('--name',default='PatientEvoPhysio_dataset'); ap.add_argument('--output',type=Path,default=ROOT/'release'); ap.add_argument('--include-data',action='store_true'); ap.add_argument('--zip',action='store_true'); a=ap.parse_args()
stamp=datetime.now(timezone.utc).strftime('%Y%m%d'); out=a.output/f'{a.name}_{stamp}';
if out.exists():shutil.rmtree(out)
out.mkdir(parents=True); (out/'metadata').mkdir(); (out/'quality').mkdir();
# ensure reports
import subprocess,sys
subprocess.run([sys.executable,str(ROOT/'scripts'/'report_all.py')],cwd=ROOT,check=False)
subprocess.run([sys.executable,str(ROOT/'scripts'/'dataset_quality_report.py')],cwd=ROOT,check=False)
# copy quality artifacts
for p in (ROOT/'data'/'quality').glob('*'):
 if p.is_file() and p.name!='.gitkeep': shutil.copy2(p,out/'quality'/p.name)
runs=[]; union=[]
for csvp in sorted(GEN.rglob('*_res.csv')):
 meta=csvp.parent/'metadata.json'; val=csvp.with_suffix('.validation.json'); sci=csvp.parent/'report'/'scientific_summary.json'
 m=json.loads(meta.read_text(encoding='utf-8')) if meta.exists() else {}; v=json.loads(val.read_text(encoding='utf-8')) if val.exists() else {}
 with csvp.open('r',encoding='utf-8-sig',newline='') as f: fields=next(csv.reader(f),[])
 for x in fields:
  if x not in union:union.append(x)
 destrel=Path('data')/m.get('run',{}).get('profile','runs')/m.get('run',{}).get('scenario_id',csvp.parent.name)/csvp.name
 if a.include_data:
  d=out/destrel;d.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(csvp,d)
 runs.append({'scenario_id':m.get('run',{}).get('scenario_id'),'profile':m.get('run',{}).get('profile'),'model':m.get('run',{}).get('model'),'start_time_s':m.get('run',{}).get('start_time'),'stop_time_s':m.get('run',{}).get('stop_time'),'intervals':m.get('run',{}).get('number_of_intervals'),'solver':m.get('run',{}).get('method'),'tolerance':m.get('run',{}).get('tolerance'),'validation_status':v.get('status'),'rows':v.get('rows'),'variables':v.get('variables'),'model_sha256':m.get('model_sha256'),'openmodelica':m.get('openmodelica'),'source_csv':csvp.relative_to(ROOT).as_posix(),'release_csv':destrel.as_posix() if a.include_data else '', 'csv_sha256':sha(csvp)})
if not runs:
 raise SystemExit('No curated generated runs found. Generate data before building a release.')
# index
fields=list(runs[0])
if runs:
 with (out/'dataset_index.csv').open('w',encoding='utf-8',newline='') as f:w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(runs)
# dictionary
with (out/'variable_dictionary.csv').open('w',encoding='utf-8',newline='') as f:
 w=csv.writer(f);w.writerow(['variable','unit','description']);
 for x in union:
  u,d=unit_desc(x);w.writerow([x,u,d])
prov={'schema_version':1,'generated_at_utc':datetime.now(timezone.utc).isoformat(),'software':'PatientEvoPhysio','software_version':(ROOT/'VERSION').read_text().strip(),'repository':'https://github.com/ehsepulvedao/PatientEvoPhysio','maintainer':{'name':'Edgar Hernando Sepúlveda-Oviedo','email':'edgar-hernando.sepulveda-oviedo@univ-perp.fr','affiliations':['PROMES-CNRS (UPR 8521), Rambla de la thermodynamique, Tecnosud, Perpignan, 66100, France','Université de Perpignan Via Domitia, 52 Avenue Paul Alduy, Perpignan, 66860, France']},'run_count':len(runs),'data_included':a.include_data,'note':'All files are synthetic/in-silico outputs generated by the documented mechanistic Modelica simulator.'}
(out/'provenance.json').write_text(json.dumps(prov,indent=2,ensure_ascii=False),encoding='utf-8')
readme=f'''# {a.name}\n\nThis package contains synthetic/in-silico cardiorespiratory data generated with PatientEvoPhysio.\n\n- Software version: {prov['software_version']}\n- Curated runs indexed: {len(runs)}\n- Data files included: {a.include_data}\n- Dataset index: `dataset_index.csv`\n- Variable dictionary: `variable_dictionary.csv`\n- Quality report: `quality/quality_report.md`\n- Provenance: `provenance.json`\n- Checksums: `SHA256SUMS.txt`\n\nThe data are intended for reproducible computational research, algorithm benchmarking, system identification and educational use. They are not clinical measurements and must not be interpreted as patient records.\n'''
(out/'README_DATASET.md').write_text(readme,encoding='utf-8')
(out/'DATA_AVAILABILITY_STATEMENT.txt').write_text('The dataset will be deposited in a public repository that assigns a persistent identifier (DOI). Replace this sentence with the final repository name, DOI and URL before manuscript submission.\n',encoding='utf-8')
(out/'LICENSE_DATA.txt').write_text('Dataset licensing follows the repository CC0-1.0 dedication unless a different license is explicitly selected before public deposit.\n',encoding='utf-8')
# checksums last
entries=[]
for p in sorted(out.rglob('*')):
 if p.is_file() and p.name!='SHA256SUMS.txt': entries.append(f'{sha(p)}  {p.relative_to(out).as_posix()}')
(out/'SHA256SUMS.txt').write_text('\n'.join(entries)+'\n',encoding='utf-8')
if a.zip:
 zp=out.with_suffix('.zip')
 if zp.exists():zp.unlink()
 with zipfile.ZipFile(zp,'w',zipfile.ZIP_DEFLATED) as z:
  for p in out.rglob('*'):
   if p.is_file():z.write(p,p.relative_to(out.parent))
 print('[OK]',zp)
else: print('[OK]',out)
